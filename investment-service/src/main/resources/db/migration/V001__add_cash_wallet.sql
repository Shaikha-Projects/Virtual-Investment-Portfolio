-- manual postgresql migration. no flyway or liquibase is required.
-- keep portfolio provisioning at $100,000 until the later coordinated cutover.
-- run this file once with psql and stop on errors
-- this file owns its transaction; do not wrap it in another transaction.
-- pause portfolio writes when comparing the before/after balance fingerprints.

BEGIN;

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

-- stabilize the portfolio structure and balances for this migration transaction.
LOCK TABLE public.portfolios IN ACCESS EXCLUSIVE MODE;

-- stop for an existing or partial migration instead of silently skipping objects.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_attribute
        WHERE attrelid = 'public.portfolios'::regclass
          AND attname = 'initial_funding'
          AND NOT attisdropped
    ) OR to_regclass('public.wallet_operations') IS NOT NULL THEN
        RAISE EXCEPTION
            'Cash wallet objects already exist. Inspect the existing or partial migration before proceeding.';
    END IF;
END
$$;

-- existing rows receive the legacy baseline without changing their cash balances.
-- the default also keeps the current provisioning insert compatible.
ALTER TABLE public.portfolios
    ADD COLUMN initial_funding numeric(15,2)
        NOT NULL DEFAULT 100000.00,
    ADD CONSTRAINT portfolios_initial_funding_nonnegative
        CHECK (initial_funding >= 0);

CREATE TABLE public.wallet_operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id bigint NOT NULL,
    reference uuid NOT NULL,
    idempotency_key varchar(128) NOT NULL,
    operation_type varchar(16) NOT NULL,
    amount numeric(15,2) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'USD',
    payment_method varchar(32),
    status varchar(16) NOT NULL,
    failure_code varchar(64),
    balance_after numeric(15,2),
    created_at timestamp(6) without time zone
        NOT NULL DEFAULT LOCALTIMESTAMP,
    completed_at timestamp(6) without time zone,

    CONSTRAINT wallet_operations_portfolio_fk
        FOREIGN KEY (portfolio_id)
        REFERENCES public.portfolios(id)
        ON DELETE RESTRICT,

    CONSTRAINT wallet_operations_reference_unique
        UNIQUE (reference),

    CONSTRAINT wallet_operations_idempotency_unique
        UNIQUE (portfolio_id, idempotency_key),

    CONSTRAINT wallet_operations_key_nonblank
        CHECK (length(btrim(idempotency_key)) > 0),

    CONSTRAINT wallet_operations_type_check
        CHECK (operation_type IN ('DEPOSIT', 'WITHDRAWAL')),

    CONSTRAINT wallet_operations_amount_check
        CHECK (amount > 0 AND amount <> 'NaN'::numeric),

    CONSTRAINT wallet_operations_currency_check
        CHECK (currency = 'USD'),

    CONSTRAINT wallet_operations_payment_method_check
        CHECK (
            (operation_type = 'DEPOSIT'
                AND payment_method IS NOT NULL
                AND length(btrim(payment_method)) > 0)
            OR
            (operation_type = 'WITHDRAWAL'
                AND payment_method IS NULL)
        ),

    CONSTRAINT wallet_operations_status_check
        CHECK (status IN ('COMPLETED', 'FAILED')),

    CONSTRAINT wallet_operations_outcome_check
        CHECK (
            (status = 'COMPLETED'
                AND failure_code IS NULL
                AND balance_after IS NOT NULL
                AND balance_after >= 0
                AND balance_after <> 'NaN'::numeric
                AND completed_at IS NOT NULL)
            OR
            (status = 'FAILED'
                AND failure_code IS NOT NULL
                AND length(btrim(failure_code)) > 0
                AND balance_after IS NULL
                AND completed_at IS NULL)
        ),

    CONSTRAINT wallet_operations_time_check
        CHECK (completed_at IS NULL OR completed_at >= created_at)
);

CREATE INDEX wallet_operations_history_idx
    ON public.wallet_operations
        (portfolio_id, created_at DESC, id DESC);

COMMIT;

